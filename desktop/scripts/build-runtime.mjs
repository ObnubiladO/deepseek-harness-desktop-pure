import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const desktop = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(desktop, '..')
const runtime = resolve(desktop, 'runtime')
const outdir = resolve(runtime, 'lib')
const deployDir = resolve(desktop, 'src-tauri/rt')

await rm(outdir, { recursive: true, force: true })
await mkdir(outdir, { recursive: true })
await writeProfileBootBridge()
await writeBridgeScriptModule()
await stageClientUiBundle()

const common = {
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  packages: 'external',
  external: ['@deepseek-ai/*'],
  sourcemap: true,
  logLevel: 'info',
}

await build({
  ...common,
  entryPoints: {
    sidecar: resolve(runtime, 'src/sidecar.ts'),
    surface: resolve(runtime, 'src/surface.ts'),
    'directory-picker': resolve(runtime, 'src/directory-picker.ts'),
    'settings-controller': resolve(runtime, 'src/settings-controller.ts'),
  },
  outdir,
  entryNames: '[name]',
  chunkNames: 'chunks/[name]-[hash]',
  outExtension: { '.js': '.mjs' },
  splitting: true,
})

await rm(deployDir, { recursive: true, force: true })

async function writeProfileBootBridge() {
  // Upstream keeps the compiled profile-boot facade at the stable
  // lib/profile-boot.js path. Its CLI launcher imports a content-hashed chunk
  // instead, so parsing bin.js for a facade import no longer works; read the
  // facade directly and fail fast if it stops exporting runProfile.
  const facade = await readFile(resolve(root, 'apps/cli/lib/profile-boot.js'), 'utf8')
  if (!/export\s*\{[^}]*\brunProfile\b/.test(facade)) {
    throw new Error('expected apps/cli/lib/profile-boot.js to export runProfile')
  }
  const bridge = "export { runProfile } from '../node_modules/@deepseek-ai/dsh/lib/profile-boot.js'\n"
  await writeFile(resolve(outdir, 'profile-boot.mjs'), bridge)
}

/**
 * Stage the desktop-only client UI bundle (the About section + update badge):
 * the source is hand-written in the `window.__ModuleLoader__.load` contract
 * (same format the harness serves for every dsh.client package) and ships
 * verbatim as lib/client.js of @deepseek-ai/dsh-desktop-client-ui.
 */
async function stageClientUiBundle() {
  const source = resolve(desktop, 'client-ui/src')
  const target = resolve(desktop, 'client-ui/lib')
  await rm(target, { recursive: true, force: true })
  await mkdir(target, { recursive: true })
  await Promise.all([
    cp(resolve(source, 'index.js'), resolve(target, 'index.js')),
    cp(resolve(source, 'client.js'), resolve(target, 'client.js')),
  ])
  process.stdout.write('staged desktop client-ui host and client bundles\n')
}

/**
 * Bundle the page-side bridge (the one desktop affordance the frontend needs)
 * and inline the minified IIFE as a text module the desktop-surface plugin
 * serves and injects through the web host's own index taps.
 */
async function writeBridgeScriptModule() {
  const result = await build({
    entryPoints: [resolve(desktop, 'bridge/src/index.ts')],
    bundle: true,
    platform: 'browser',
    target: ['safari15', 'chrome105'],
    format: 'iife',
    minify: true,
    write: false,
    logLevel: 'info',
  })
  const bridgeSource = result.outputFiles[0].text
  await writeFile(
    resolve(runtime, 'src/bridge-script.generated.ts'),
    `// generated by desktop/scripts/build-runtime.mjs — do not edit\nexport const bridgeScript = ${JSON.stringify(bridgeSource)}\n`,
  )
}
